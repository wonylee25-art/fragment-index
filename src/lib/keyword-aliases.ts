// RISS에서 받아오는 주제어는 논문마다 저자가 적은 그대로라, 같은 것을 두고 표기가 갈린다.
// 원본(papers.keywords)은 건드리지 않고, 읽을 때만 대표어로 묶어 보여준다 — 여기서 한 줄
// 지우면 그대로 다시 갈라지고, RISS를 다시 받아도 정리가 깨지지 않는다.
//
// 여럿을 한 이름 아래 몰아넣을 때 — 「대표: [변형, 변형, …]」로 적는 편이 읽기 쉽다.
function under(target: string, sources: string[]): Record<string, string> {
  return Object.fromEntries(sources.map((source) => [source, target]));
}

