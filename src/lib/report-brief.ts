//
// report-summary.ts는 겹치는 머리(용역명·기간·용역사)를 걷는 기계 규칙이다. 그것만으로는
// 모자란다 — PRISM이 준 요약 칸은 절반이 초록이 아니라 발주 문서의 「과업 개요」라서,
// 머리를 걷고 나도 항목 나열이 열 줄씩 남고 과제마다 꼴이 다 다르다. 어떤 것은 전사 지침을
