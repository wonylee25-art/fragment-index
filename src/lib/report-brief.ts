// 목록에서 알고 싶은 것은 둘뿐이다 — **누구를 채록했나(대상)**, **무엇을 했나(내용)**.
// 그래서 48건을 읽고 그 둘만 남겼다. 규칙 셋을 지켰다:
//
//   1. 원문에 없는 것은 적지 않는다. 대상을 안 밝힌 과제는 target을 비운다.
//   2. 사람 수·시간·이름처럼 원문이 밝힌 수치는 그대로 옮긴다.
//   3. 요약 칸이 제목을 되풀이할 뿐인 것은 null로 둔다 — 화면에서 아무것도 세우지 않는다.
//
// **원문은 DB에 그대로 남는다.** 검색은 research_summary 원문을 훑으므로, 여기서 줄인 말에
// 없는 낱말로도 찾힌다. 여기 없는 id(손으로 넣은 보고서, PRISM이 요약을 비워 둔 3건)는
// 예전대로 trimReportSummary가 맡는다.

